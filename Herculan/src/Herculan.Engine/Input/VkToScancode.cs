using Silk.NET.Input;

namespace Herculan.Engine.Input;

/// <summary>
/// DBSIM's <c>VkToScancode</c> (<c>004a1104</c>): the 223 int32 entries <c>Key_WndProcHook</c> (<c>00477ae0</c>) indexes
